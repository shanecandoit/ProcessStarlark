#!/bin/sh
# Validate Go and the playground, then build the static site. Run from anywhere.
set -eu
cd "$(dirname "$0")"

go fmt ./...
go test ./...
go vet ./...
GOOS=js GOARCH=wasm go vet ./cmd/park-wasm
go build ./...
sh web/build.sh
printf 'Build passed. Playground ready in %s/web/dist\nServe with: python3 -m http.server -d "%s/web/dist" 8000\n' "$PWD" "$PWD"
